const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

function readEnvLocal() {
  const envPath = path.join(__dirname, '..', '.env.local');
  const contents = fs.readFileSync(envPath, 'utf-8').replace(/^\uFEFF/, '');
  const env = {};
  contents.split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIndex = trimmed.indexOf('=');
    if (eqIndex === -1) return;
    env[trimmed.slice(0, eqIndex).trim()] = trimmed.slice(eqIndex + 1).trim();
  });
  return env;
}

const JOB_NAME = 'entry-digest-daily';
const SECRET_NAME = 'digest_cron_secret';
const SCHEDULE = '0 4 * * *'; // 04:00 UTC = 06:00 South African time

async function run() {
  const env = readEnvLocal();
  const missing = ['DATABASE_URL', 'CRON_SECRET', 'APP_URL'].filter((k) => !env[k]);
  if (missing.length > 0) {
    console.error('Missing in .env.local:', missing.join(', '));
    return;
  }

  const endpoint = `${env.APP_URL.replace(/\/+$/, '')}/api/cron/entry-digest`;
  if (!/^https:\/\/[^\s']+$/.test(endpoint)) {
    console.error('APP_URL must be a full https:// address.');
    return;
  }

  const client = new Client({ connectionString: env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
  await client.connect();

  try {
    await client.query('BEGIN');

    await client.query(`
      create table if not exists public.digest_log (
        id bigint generated by default as identity primary key,
        run_at timestamp with time zone not null default now(),
        sent boolean not null default false,
        open_events integer not null default 0,
        new_entries integer not null default 0,
        error text
      )
    `);
    await client.query(`alter table public.digest_log enable row level security`);
    await client.query(`revoke all on public.digest_log from anon, authenticated`);
    await client.query(`grant all on public.digest_log to service_role`);

    await client.query(`create extension if not exists pg_cron`);
    await client.query(`create extension if not exists pg_net with schema extensions`);

    const existing = await client.query('select id from vault.secrets where name = $1', [SECRET_NAME]);
    if (existing.rowCount > 0) {
      await client.query('select vault.update_secret($1::uuid, $2::text)', [existing.rows[0].id, env.CRON_SECRET]);
    } else {
      await client.query('select vault.create_secret($1::text, $2::text, $3::text)', [
        env.CRON_SECRET,
        SECRET_NAME,
        'Shared secret for the entry digest route',
      ]);
    }

    const command = `select net.http_post(
  url := '${endpoint}',
  headers := jsonb_build_object(
    'Content-Type', 'application/json',
    'Authorization', 'Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name = '${SECRET_NAME}')
  ),
  body := '{}'::jsonb,
  timeout_milliseconds := 30000
);`;
    await client.query('select cron.schedule($1, $2, $3)', [JOB_NAME, SCHEDULE, command]);

    await client.query('COMMIT');

    const job = await client.query('select jobid, jobname, schedule, active from cron.job where jobname = $1', [JOB_NAME]);
    console.log('✅ Digest set up.');
    console.table(job.rows);
    console.log(`It will call ${endpoint} every day at 04:00 UTC (06:00 South African time).`);
  } catch (err) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // nothing to roll back
    }
    console.error('❌ Setup failed, nothing was changed:', err.message);
  } finally {
    await client.end();
  }
}

run();