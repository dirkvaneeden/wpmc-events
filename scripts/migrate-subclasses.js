const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

function readEnvLocal() {
  const envPath = path.join(__dirname, '..', '.env.local');
  const contents = fs.readFileSync(envPath, 'utf-8').replace(/^\uFEFF/, '');
  const env = {};
  contents.split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIndex = trimmed.indexOf('=');
    if (eqIndex === -1) return;
    env[trimmed.slice(0, eqIndex).trim()] = trimmed.slice(eqIndex + 1).trim();
  });
  return env;
}

const sql = `
create table if not exists public.race_subclasses (
  id bigint generated by default as identity primary key,
  class_id integer not null references public.race_classes(id) on delete cascade,
  name character varying(100) not null,
  created_at timestamp with time zone not null default now(),
  constraint race_subclasses_class_id_name_key unique (class_id, name)
);

create index if not exists race_subclasses_class_id_idx on public.race_subclasses (class_id);

alter table public.event_entries add column if not exists subclass_id bigint references public.race_subclasses(id);
create index if not exists event_entries_subclass_id_idx on public.event_entries (subclass_id);

alter table public.race_subclasses enable row level security;
drop policy if exists "Anyone can view sub classes" on public.race_subclasses;
drop policy if exists "Admins insert sub classes" on public.race_subclasses;
drop policy if exists "Admins update sub classes" on public.race_subclasses;
drop policy if exists "Admins delete sub classes" on public.race_subclasses;
create policy "Anyone can view sub classes" on public.race_subclasses for select using (true);
create policy "Admins insert sub classes" on public.race_subclasses for insert with check (is_admin());
create policy "Admins update sub classes" on public.race_subclasses for update using (is_admin());
create policy "Admins delete sub classes" on public.race_subclasses for delete using (is_admin());

grant select on public.race_subclasses to anon, authenticated;
grant insert, update, delete on public.race_subclasses to authenticated;
grant all on public.race_subclasses to service_role;

create or replace function public.class_entry_list(p_entry_id uuid)
returns table (
  race_number text,
  driver_name text,
  vehicle text,
  subclass_name text,
  is_you boolean,
  confirmed boolean
)
language sql
security definer
set search_path = public
stable
as $$
  select
    e.race_number::text,
    d.full_name::text,
    trim(concat_ws(' ', v.year::text, v.make, v.model)),
    sc.name::text,
    (e.id = p_entry_id),
    (e.status = 'PAID' or e.fee_amount <= 0)
  from public.event_entries mine
  join public.drivers md on md.id = mine.driver_id
  join public.event_entries e on e.event_id = mine.event_id and e.class_id = mine.class_id
  join public.drivers d on d.id = e.driver_id
  join public.vehicles v on v.id = e.vehicle_id
  left join public.race_subclasses sc on sc.id = e.subclass_id
  where mine.id = p_entry_id
    and md.auth_user_id = auth.uid()
    and (e.id = p_entry_id or e.status = 'PAID' or e.fee_amount <= 0)
$$;

revoke all on function public.class_entry_list(uuid) from public;
revoke all on function public.class_entry_list(uuid) from anon;
grant execute on function public.class_entry_list(uuid) to authenticated;
`;

async function run() {
  const env = readEnvLocal();
  if (!env.DATABASE_URL) {
    console.error('Missing DATABASE_URL in .env.local');
    return;
  }

  const client = new Client({ connectionString: env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
  await client.connect();

  try {
    await client.query('BEGIN');
    await client.query(sql);
    await client.query('COMMIT');
    await client.query(`notify pgrst, 'reload schema'`);
    console.log('✅ Sub classes table, entries.subclass_id and class_entry_list() are in place.');
  } catch (err) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // nothing to roll back
    }
    console.error('❌ Migration failed, nothing was changed:', err.message);
  } finally {
    await client.end();
  }
}

run();